/**
 * Import the canonical Markdown in `packages/vx/docs/`, and each published
 * plugin's README as `plugins/<package>.md`, into the Starlight content
 * collection. That tree stays the single source of truth;
 * this script adds frontmatter and rewrites internal `.md` links to
 * Starlight clean URLs. It is idempotent and runs before every dev/build.
 *
 * Hand-authored pages (quickstart, guides/, concepts/, migrate/) are never touched —
 * this script only writes the generated set listed in GENERATED below.
 * Its transforms are exported for tests/import-docs.test.ts (item 837); the
 * run happens only when this file is the entry point.
 */
