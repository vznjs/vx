/**
 * Regenerate `outDir`'s imported pages from `docsDir`. Returns how many
 * sources it imported.
 */
export async function importDocs(
  docsDir = DOCS_DIR,
  outDir = OUT_DIR,
  packagesDir = PACKAGES_DIR,
): Promise<number> {
  const sources = collectSources(docsDir)
  const linkMap = buildLinkMap(sources)

  // Two sources on one output keep whichever the scan wrote last, silently.
  const outputs = new Map<string, string>()
  for (const srcRel of sources) {
    const outRel = outRelFor(srcRel)
    const other = outputs.get(outRel)
    if (other) throw new Error(`import-docs: ${other} and ${srcRel} both write ${outRel}`)
    outputs.set(outRel, srcRel)
  }

  // Every generated page goes first, so a source deleted from docs/ does not
  // keep a stale page on the site (differentiators.md outlived its source by
  // one build, 2026-09-03). A name manifest cannot do this — a deleted source
  // is exactly the name a manifest no longer has — so generated pages are
  // self-describing: each carries GENERATED_MARK in its frontmatter, and any
  // page carrying it is cleared, at any depth (`compare/turbo-nx-support.md`
  // sits beside an authored page). Authored pages never carry it.
  await mkdir(outDir, { recursive: true })
  for (const f of new Glob('**/*.md').scanSync({ cwd: outDir })) {
    const head = (await Bun.file(path.join(outDir, f)).text()).slice(0, 400)
    if (head.includes(GENERATED_MARK)) await rm(path.join(outDir, f), { force: true })
  }
  for (const entry of ['modules', 'design', 'plugins', 'cli', 'schema']) {
    await rm(path.join(outDir, entry), { recursive: true, force: true })
  }

  const designFiles: { url: string; title: string; description?: string }[] = []

  const splits = new Map<string, SplitReference & { base: string }>()
  for (const { src, base, specs, list } of SPLIT_REFERENCES) {
    const file = Bun.file(path.join(docsDir, src))
    if (!(await file.exists())) continue
    splits.set(src, { ...splitReference(await file.text(), specs, list), base })
  }
  // Every split is known before any page is written: a CLI page links schema/ ids too.
  function relinkAll(text: string, url: string): string {
    let out = text
    for (const s of splits.values()) out = relink(out, url, s.base, s.anchors)
    return out
  }
  for (const [src, { base, pages }] of splits) {
    await mkdir(path.join(outDir, base), { recursive: true })
    for (const { page, markdown } of pages) {
      const url = `${base}${page}/`
      await Bun.write(
        path.join(outDir, base, `${page}.md`),
        relinkAll(transformFile(src, markdown, linkMap, url), url),
      )
    }
  }

  for (const srcRel of sources) {
    const split = splits.get(srcRel)
    const content = split?.index ?? (await Bun.file(path.join(docsDir, srcRel)).text())
    const transformed =
      relinkAll(transformFile(srcRel, content, linkMap), cleanUrlFor(srcRel)) +
      (split ? `\n${split.forward}\n` : '')
    const outRel = outRelFor(srcRel)
    const outPath = path.join(outDir, outRel)
    await mkdir(path.dirname(outPath), { recursive: true })
    await Bun.write(outPath, transformed)

    if (srcRel.startsWith('design/')) {
      const m = /^title:\s*(.+)$/m.exec(transformed)
      const title = m ? JSON.parse(m[1]!) : srcRel
      const d = /^description:\s*(.+)$/m.exec(transformed)
      const description = d ? JSON.parse(d[1]!) : undefined
      designFiles.push({ url: cleanUrlFor(srcRel), title, description })
    }
  }

  await Bun.write(path.join(outDir, 'design/index.md'), designIndex(designFiles))

  const plugins = pluginPackages(packagesDir)
  for (const dir of plugins) {
    const readme = await Bun.file(path.join(packagesDir, dir, 'README.md')).text()
    await Bun.write(path.join(outDir, 'plugins', `${dir}.md`), transformReadme(dir, readme))
  }
  return sources.length + plugins.length
}

if (import.meta.main) {
  const count = await importDocs()
  console.log(`imported ${count} docs → ${path.relative(process.cwd(), OUT_DIR)}`)
}
