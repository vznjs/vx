// ---- path helpers (POSIX, within the docs tree) ----

function normalize(p: string): string {
  const parts = p.split('/')
  const out: string[] = []
  for (const part of parts) {
    if (part === '' || part === '.') continue
    if (part === '..') out.pop()
    else out.push(part)
  }
  return out.join('/')
}

/** docs-relative source path (e.g. "modules/cache.md") -> clean URL ("modules/cache/"). */
export function cleanUrlFor(srcRel: string): string {
  if (srcRel === 'README.md') return 'overview/'
  if (srcRel === 'modules/README.md') return 'modules/'
  if (srcRel === 'modules/index.md') return 'modules/public-surface/'
  if (srcRel === 'turbo-nx-support.md') return 'compare/turbo-nx-support/'
  // `features/` is the Features hub (src/pages/features/).
  if (srcRel === 'features.md') return 'all-features/'
  // Astro slugs each path segment (github-slugger), which lowercases and
  // drops punctuation: `design/roadmap-1.0.md` is served at
  // `design/roadmap-10/`. tests/site-links.test.ts holds the two to agree.
  const noExt = srcRel
    .replace(/\.md$/i, '')
    .toLowerCase()
    .replace(/[^a-z0-9/_-]/g, '')
  return `${noExt}/`
}

/** docs-relative source path -> output file path within the content collection. */
export function outRelFor(srcRel: string): string {
  if (srcRel === 'README.md') return 'overview.md'
  if (srcRel === 'modules/README.md') return 'modules/index.md'
  // `src/index.ts`'s page would be the directory's index too: both wrote
  // `modules/index.md`, and the scan's order chose which page the site kept.
  if (srcRel === 'modules/index.md') return 'modules/public-surface.md'
  // Beside the hand-authored compare page, whose URL it extends.
  if (srcRel === 'turbo-nx-support.md') return 'compare/turbo-nx-support.md'
  if (srcRel === 'features.md') return 'all-features.md'
  return srcRel
}

// ---- collect sources & build the link map ----

function collectSources(docsDir: string): string[] {
  const sources: string[] = []
  for (const pattern of ['*.md', 'modules/*.md', 'design/*.md']) {
    for (const f of new Glob(pattern).scanSync({ cwd: docsDir })) {
      // STATUS.md is the maintainers' handoff, not user documentation.
      if (f === 'STATUS.md') continue
      sources.push(f.split(path.sep).join('/'))
    }
  }
  return sources
}

/** key (no extension, no trailing slash) -> clean URL. */
export function buildLinkMap(sources: readonly string[]): Map<string, string> {
  const linkMap = new Map<string, string>()
  for (const srcRel of sources) {
    const key = srcRel.replace(/\.md$/i, '')
    linkMap.set(key, cleanUrlFor(srcRel))
  }
  // directory links: ./modules/ and ./design/ resolve to their index pages.
  linkMap.set('modules', 'modules/')
  linkMap.set('design', 'design/')
  return linkMap
}

// ---- link rewriting ----

type LinkMap = ReadonlyMap<string, string>

function resolveInternal(
  url: string,
  sourceDir: string,
  prefix: string,
  linkMap: LinkMap,
): string | null {
  if (/^[a-z][a-z0-9+.-]*:/i.test(url) || url.startsWith('#') || url.startsWith('//')) {
    return null
  }
  const hash = url.indexOf('#')
  const pathPart = hash === -1 ? url : url.slice(0, hash)
  const anchor = hash === -1 ? '' : url.slice(hash)
  if (pathPart === '') return null

  const resolved = normalize(sourceDir ? `${sourceDir}/${pathPart}` : pathPart)
  const key = resolved.replace(/\/$/, '').replace(/\.md$/i, '')
  const target = linkMap.get(key)
  if (!target) return null
  return `${prefix}${target}${anchor}`
}

const LINK_RE = /\]\(([^)\s]+)(\s+"[^"]*")?\)/g
// vx placeholder convention in prose: <hash>, <cacheDir>, <rel>, … — escape
// so Markdown doesn't treat them as raw HTML tags. Conservative: letters then
// only word / . / / * / - chars (no ':' so autolinks like <https://…> survive).
const PLACEHOLDER_RE = /<([A-Za-z][\w./*-]*)>/g

function transformText(text: string, sourceDir: string, prefix: string, linkMap: LinkMap): string {
  const linked = text.replace(LINK_RE, (whole, url: string, title = '') => {
    const rewritten = resolveInternal(url, sourceDir, prefix, linkMap)
    return rewritten ? `](${rewritten}${title})` : whole
  })
  return linked.replace(PLACEHOLDER_RE, '&lt;$1&gt;')
}

/** Transform a prose line, leaving inline `code spans` untouched. */
function transformProse(line: string, sourceDir: string, prefix: string, linkMap: LinkMap): string {
  let out = ''
  let i = 0
  while (i < line.length) {
    if (line[i] === '`') {
      let n = 0
      while (line[i + n] === '`') n++
      const fence = '`'.repeat(n)
      const close = line.indexOf(fence, i + n)
      if (close === -1) {
        // Unterminated code span — treat the remainder as prose.
        out += transformText(line.slice(i), sourceDir, prefix, linkMap)
        break
      }
      out += line.slice(i, close + n) // code span verbatim
      i = close + n
    } else {
      let j = i
      while (j < line.length && line[j] !== '`') j++
      out += transformText(line.slice(i, j), sourceDir, prefix, linkMap)
      i = j
    }
  }
  return out
}

// ---- per-file transform ----

const yaml = (s: string) => JSON.stringify(s)

export function deriveDescription(lines: string[]): string {
  // A paragraph, not a line: a skipped paragraph (a bold status note, a
  // list) must not hand its second line to the description.
  const paragraphs: string[] = []
  let current: string[] = []
  let fenced = false
  for (const raw of [...lines, '']) {
    const line = raw.trim()
    if (line.startsWith('```')) fenced = !fenced
    if (fenced || line.startsWith('```')) continue
    if (line !== '') current.push(line)
    else if (current.length > 0) {
      paragraphs.push(current.join(' '))
      current = []
    }
  }
  // A status note or a README's link line describes the page only when
  // nothing else does.
  const fallback = /^\*\*Status|^Website:/i
  const ranked = [
    ...paragraphs.filter((p) => !fallback.test(p)),
    ...paragraphs.filter((p) => fallback.test(p)),
  ]
  for (const para of ranked) {
    if (/^[#>|-]|^\* |^\d+\.|^<|^!\[|^:::/.test(para)) continue
    const plain = para
      .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
      .replace(/[`*_]/g, '')
      .replace(/<([A-Za-z][\w./*-]*)>/g, '$1')
      .replace(/\s+/g, ' ')
      .trim()
    if (plain.length < 24) continue
    return plain.length > 158 ? `${plain.slice(0, 157).replace(/\s+\S*$/, '')}…` : plain
  }
  return ''
}

/** `url` serves the page somewhere other than srcRel's own URL (a CLI command's page). */
export function transformFile(
  srcRel: string,
  content: string,
  linkMap: LinkMap,
  url = cleanUrlFor(srcRel),
): string {
  const cleanUrl = url
  const depth = cleanUrl.replace(/\/$/, '').split('/').length
  const prefix = '../'.repeat(depth)
  const sourceDir = srcRel.includes('/') ? srcRel.slice(0, srcRel.lastIndexOf('/')) : ''

  const lines = content.replace(/\r\n/g, '\n').split('\n')

  // Pull the first H1 as the page title and drop it (Starlight renders the
  // frontmatter title as the page heading).
  let title = ''
  let titleIdx = -1
  for (let i = 0; i < lines.length; i++) {
    const m = /^#\s+(.+?)\s*$/.exec(lines[i]!)
    if (m) {
      title = m[1]!.replace(/`/g, '').trim()
      titleIdx = i
      break
    }
  }
  if (titleIdx !== -1) lines.splice(titleIdx, 1)
  if (!title) {
    const base = path.basename(srcRel, '.md')
    title = base === 'README' ? 'Overview' : base
  }

  const description = deriveDescription(lines)

  // Transform body line-by-line, skipping fenced code blocks.
  let inFence = false
  let fenceMarker = ''
  const body = lines.map((line) => {
    const fence = /^\s*(```+|~~~+)/.exec(line)
    if (fence) {
      if (!inFence) {
        inFence = true
        fenceMarker = fence[1]![0]!
      } else if (line.trimStart().startsWith(fenceMarker)) {
        inFence = false
      }
      return line
    }
    return inFence ? line : transformProse(line, sourceDir, prefix, linkMap)
  })

  const fm = ['---', GENERATED_MARK, `title: ${yaml(title)}`]
  if (description) fm.push(`description: ${yaml(description)}`)
  // "Edit page" must open the source, not the generated copy: the site's
  // `editLink.baseUrl` serves the hand-authored pages, so each imported
  // page names its own file under packages/vx/docs/.
  fm.push(`editUrl: ${yaml(`https://github.com/vznjs/vx/edit/main/packages/vx/docs/${srcRel}`)}`)
  fm.push('---', '')
  return `${fm.join('\n')}${body.join('\n').replace(/^\n+/, '')}`
}

