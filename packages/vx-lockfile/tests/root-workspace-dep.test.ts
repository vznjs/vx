// A workspace package the root depends on is installed at the root
// `node_modules`, so every project resolves it whatever its own manifest
// says. app declares nothing and requires lib through the root: without an
// edge, an edit to lib re-keyed only lib, `--affected` left app out and
// app#build replayed the old lib (Turbo #8364, #8465; Growth,
// chunk-03-root-workspace-dep.sh). The root → lib; lib → util, so util → lib
// would close a cycle and is reach only. Shapes as each manager writes them.
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'bun:test'
import type { Logger } from '@vzn/vx'
import { planRun } from '../../vx/tests/helpers/orchestrator.js'
import { affectedIds, commitAll } from './helpers/affected.js'
import { localWorkspaceSource } from './helpers/local-workspace.js'

const PLUGIN_INDEX = path.resolve(import.meta.dir, '..', 'src', 'index.ts')

const PNPM = `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    devDependencies:
      lib:
        specifier: workspace:*
        version: link:packages/lib

  packages/app: {}

  packages/lib:
    dependencies:
      util:
        specifier: workspace:*
        version: link:../util

  packages/util: {}
`

const BUN = `{
  "lockfileVersion": 1,
  "workspaces": {
    "": { "name": "root", "devDependencies": { "lib": "workspace:*" } },
    "packages/app": { "name": "app" },
    "packages/lib": { "name": "lib", "dependencies": { "util": "workspace:*" } },
    "packages/util": { "name": "util" },
  },
  "packages": {
    "app": ["app@workspace:packages/app"],
    "lib": ["lib@workspace:packages/lib"],
    "util": ["util@workspace:packages/util"],
  }
}
`

const NPM = JSON.stringify({
  name: 'root',
  lockfileVersion: 3,
  requires: true,
  packages: {
    '': { name: 'root', workspaces: ['packages/*'], devDependencies: { lib: '*' } },
    'node_modules/app': { resolved: 'packages/app', link: true },
    'node_modules/lib': { resolved: 'packages/lib', link: true },
    'node_modules/util': { resolved: 'packages/util', link: true },
    'packages/app': { version: '1.0.0' },
    'packages/lib': { version: '1.0.0', dependencies: { util: '*' } },
    'packages/util': { version: '1.0.0' },
  },
})

const YARN = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 10
  cacheKey: 10c0

"app@workspace:packages/app":
  version: 0.0.0-use.local
  resolution: "app@workspace:packages/app"
  languageName: unknown
  linkType: soft

"lib@workspace:*, lib@workspace:packages/lib":
  version: 0.0.0-use.local
  resolution: "lib@workspace:packages/lib"
  dependencies:
    util: "workspace:*"
  languageName: unknown
  linkType: soft

"root@workspace:.":
  version: 0.0.0-use.local
  resolution: "root@workspace:."
  dependencies:
    lib: "workspace:*"
  languageName: unknown
  linkType: soft

"util@workspace:*, util@workspace:packages/util":
  version: 0.0.0-use.local
  resolution: "util@workspace:packages/util"
  languageName: unknown
  linkType: soft
`

// Yarn classic records no workspace: its links are the manifests'.
const YARN_CLASSIC = '# yarn lockfile v1\n\n\n'

const CASES = [
  { name: 'pnpm', file: 'pnpm-lock.yaml', text: PNPM },
  { name: 'bun', file: 'bun.lock', text: BUN },
  { name: 'npm', file: 'package-lock.json', text: NPM },
  { name: 'yarn', file: 'yarn.lock', text: YARN },
  { name: 'yarn', file: 'yarn.lock', text: YARN_CLASSIC, label: 'yarn() classic' },
] as const

const BUILD = `export default { tasks: { build: { dependsOn: ['^build'], exec: { command: 'echo built' }, inputs: { files: ['src/**'] }, cache: { outputs: { files: [] } } } } }\n`

function silent(): Logger {
  return {
    runStart() {},
    taskStart() {},
    taskStdout() {},
    taskStderr() {},
    taskComplete() {},
    runStatus() {},
    runEnd() {},
    status() {},
  } as never
}

let root: string
beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'vx-root-dep-'))
})
afterEach(async () => {
  await rm(root, { recursive: true, force: true })
})

async function setup(c: (typeof CASES)[number]): Promise<void> {
  await writeFile(
    path.join(root, 'package.json'),
    JSON.stringify({
      name: 'root',
      private: true,
      workspaces: ['packages/*'],
      devDependencies: { lib: 'workspace:*' },
    }),
  )
  if (c.name === 'pnpm') {
    await writeFile(path.join(root, 'pnpm-workspace.yaml'), 'packages:\n  - packages/*\n')
  }
  const manifests: Record<string, object> = {
    app: { name: 'app', version: '1.0.0' },
    lib: { name: 'lib', version: '1.0.0', dependencies: { util: 'workspace:*' } },
    util: { name: 'util', version: '1.0.0' },
  }
  for (const [name, pkg] of Object.entries(manifests)) {
    const dir = path.join(root, 'packages', name)
    await mkdir(path.join(dir, 'src'), { recursive: true })
    await writeFile(path.join(dir, 'package.json'), JSON.stringify(pkg))
    await writeFile(path.join(dir, 'src', 'index.js'), `// ${name}\n`)
    await writeFile(path.join(dir, 'vx.config.mjs'), BUILD)
  }
  await writeFile(path.join(root, c.file), c.text)
  await Bun.write(
    path.join(root, '.vx/workspace.mjs'),
    localWorkspaceSource(
      [`${c.name}()`],
      `import { ${c.name} } from ${JSON.stringify(PLUGIN_INDEX)}\n`,
    ),
  )
  Bun.spawnSync({ cmd: ['git', 'init', '-q'], cwd: root })
}

describe("a workspace package the root depends on is every project's dependency", () => {
  for (const c of CASES) {
    const label = 'label' in c ? c.label : `${c.name}()`
    it(`${label}: orders and keys every project after it, a cycle aside`, async () => {
      await setup(c)
      const plan = async () =>
        new Map(
          (await planRun({ cwd: root, tasks: ['build'], log: silent() })).tasks.map((t) => [
            t.node.id,
            t,
          ]),
        )
      const before = await plan()
      expect(before.get('app#build')!.node.deps).toEqual(['lib#build'])
      expect(before.get('lib#build')!.node.deps).toEqual(['util#build'])
      // util → lib would close lib → util: no order, so no cycle.
      expect(before.get('util#build')!.node.deps).toEqual([])
      commitAll(root)
      await writeFile(path.join(root, 'packages/lib/src/index.js'), '// lib v2\n')
      const after = await plan()
      const moved = [...after.keys()].filter((id) => after.get(id)!.hash !== before.get(id)!.hash)
      expect(moved.sort()).toEqual(['app#build', 'lib#build'])
      // util reaches lib through the root all the same: selected.
      expect(affectedIds(root, 'build')).toEqual(['app#build', 'lib#build', 'util#build'])
    })
  }
})
