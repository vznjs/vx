for (const [row, lock] of Object.entries(LOCKS)) {
  // Yarn classic keys the whole lockfile: every project moves with it.
  const reaches = lock.reaches ?? ['lib#build']
  describe(`${row}: a directory dependency beside the repository`, () => {
    let box: string
    let root: string
    beforeEach(async () => {
      box = await realpath(await mkdtemp(path.join(tmpdir(), `vx-outside-dir-${lock.pm}-`)))
      root = path.join(box, 'repo')
      await mkdir(path.join(box, 'outside/dep'), { recursive: true })
      await writeFile(
        path.join(box, 'outside/dep/package.json'),
        JSON.stringify({ name: 'dep', version: '1.0.0' }),
      )
      await writeFile(path.join(box, 'outside/dep/index.js'), '// dep v1\n')
      await mkdir(root)
      await writeFile(
        path.join(root, 'package.json'),
        JSON.stringify({ name: 'r', private: true, workspaces: ['packages/*'] }),
      )
      await writeFile(path.join(root, 'pnpm-workspace.yaml'), 'packages:\n  - packages/*\n')
      for (const name of ['lib', 'other']) {
        const dir = path.join(root, 'packages', name)
        await mkdir(path.join(dir, 'src'), { recursive: true })
        const deps = name === 'lib' ? { dependencies: { dep: lock.spec } } : {}
        await writeFile(
          path.join(dir, 'package.json'),
          JSON.stringify({ name, version: '1.0.0', ...deps }),
        )
        await writeFile(path.join(dir, 'src', 'index.js'), `// ${name}\n`)
        await writeFile(path.join(dir, 'vx.config.mjs'), BUILD)
      }
      await writeFile(path.join(root, lock.file), lock.text)
      await Bun.write(
        path.join(root, '.vx/workspace.mjs'),
        localWorkspaceSource(
          [`${lock.pm}()`],
          `import { ${lock.pm} } from ${JSON.stringify(PLUGIN_INDEX)}\n`,
        ),
      )
      Bun.spawnSync({ cmd: ['git', 'init', '-q'], cwd: root })
    })
    afterEach(async () => {
      await rm(box, { recursive: true, force: true })
    })

    const hashes = async (): Promise<Record<string, string>> => {
      const plan = await planRun({ cwd: root, tasks: ['build'], log: silent() })
      return Object.fromEntries(plan.tasks.map((t) => [t.node.id, t.hash]))
    }

    it('an edit inside the directory re-keys the projects reaching it', async () => {
      const before = await hashes()
      // CONTROL: nothing changed, nothing moves.
      expect(moved(before, await hashes())).toEqual([])
      await writeFile(path.join(box, 'outside/dep/index.js'), '// dep v2\n')
      expect(moved(before, await hashes())).toEqual([...reaches])
    })

    // Git holds no base for a directory outside the repository: a diff that
    // changes no lockfile selects nothing for it, and must not fail.
    it('--affected reads no base for the directory, and does not fail', async () => {
      await hashes()
      commitAll(root)
      await writeFile(path.join(box, 'outside/dep/index.js'), '// dep v2\n')
      expect(affectedIds(root, 'build')).toEqual([])
    })

    it('a file added to the directory re-keys the projects reaching it', async () => {
      const before = await hashes()
      await writeFile(path.join(box, 'outside/dep/extra.js'), '// new\n')
      expect(moved(before, await hashes())).toEqual([...reaches])
    })
  })
}
