const CASES = [
  { name: 'pnpm', file: 'pnpm-lock.yaml', text: PNPM, make: pnpm },
  { name: 'bun', file: 'bun.lock', text: BUN, make: bun },
  { name: 'npm', file: 'package-lock.json', text: NPM, make: npm },
  { name: 'yarn', file: 'yarn.lock', text: YARN, make: yarn },
] as const

let root: string
beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'vx-discover-'))
})
afterEach(async () => {
  await rm(root, { recursive: true, force: true })
})

/**
 * The projects core found: the root, a, b, c, d (no e). Their manifests
 * record no workspace dependency, only the peers pnpm needs to tell its
 * auto-installed peers apart: the edges below are the lockfile's.
 */
function projects(): ProjectMeta[] {
  const meta = (name: string, dir: string, peers?: Record<string, string>): ProjectMeta => ({
    name,
    dir,
    configPath: null,
    packageJson: { name, ...(peers === undefined ? {} : { peerDependencies: peers }) },
  })
  return [
    meta('root', root),
    meta('a', path.join(root, 'packages/a'), { c: 'workspace:*' }),
    meta('b', path.join(root, 'packages/b')),
    meta('c', path.join(root, 'packages/c')),
    meta('d', path.join(root, 'packages/d'), { a: 'workspace:*' }),
  ]
}

async function discover(
  plugin: VxPlugin,
  metas: ProjectMeta[] = projects(),
  warnings: string[] = [],
) {
  const ctx: DiscoverContext = {
    workspaceRoot: root,
    cacheDir: path.join(root, '.vx', 'cache'),
    projects: metas,
    warn: (m) => warnings.push(m),
    worktreeChanges: async () => null,
  }
  const rel = (dir: string) => path.relative(root, dir) || '.'
  return (await plugin.discover!(ctx)).map((e) => ({
    dir: rel(e.dir),
    name: e.name,
    deps: (e.deps ?? []).map(rel),
    reach: (e.reach ?? []).map(rel),
  }))
}

const EXPECTED = [
  { dir: 'packages/a', name: 'a', deps: ['packages/b', 'packages/c'], reach: [] },
  { dir: 'packages/b', name: 'b', deps: [], reach: [] },
  { dir: 'packages/c', name: 'c', deps: ['packages/d'], reach: [] },
  { dir: 'packages/d', name: 'd', deps: [], reach: ['packages/a'] },
  { dir: '.', name: 'root', deps: ['packages/b'], reach: [] },
]

describe('discover', () => {
  for (const c of CASES) {
    it(`${c.name}(): importers, names and edges are the lockfile's, not the manifests'`, async () => {
      await writeFile(path.join(root, c.file), c.text)
      expect(await discover(c.make())).toEqual(EXPECTED)
    })
  }

  it('no lockfile: no entries', async () => {
    expect(await discover(bun())).toEqual([])
  })

  it('a name two importers share is given to neither', async () => {
    await writeFile(path.join(root, 'bun.lock'), BUN)
    const metas = projects()
    ;(metas[2]!.packageJson as { name: string }).name = 'a'
    const names = (await discover(bun(), metas)).map((e) => e.name)
    expect(names).toEqual([undefined, undefined, 'c', 'd', 'root'])
  })

  it('pnpm(): a lockfile dependency the manifest declares only as a peer is a peer', async () => {
    // pnpm writes an auto-installed peer under `dependencies`; read as an
    // installed entry, d → a closed a → c → d → a and `^build` cycled.
    await writeFile(path.join(root, 'pnpm-lock.yaml'), PNPM)
    const metas = projects().map((m) => ({ ...m, packageJson: { name: m.name } }))
    const got = await discover(pnpm(), metas)
    expect(got.find((e) => e.dir === 'packages/d')?.deps).toEqual(['packages/a'])
    expect(await discover(pnpm())).toEqual(EXPECTED)
  })

  it('yarn(): a classic lockfile gives no edges and says why', async () => {
    await writeFile(
      path.join(root, 'yarn.lock'),
      '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\nis-number@^7.0.0:\n  version "7.0.0"\n',
    )
    const warnings: string[] = []
    expect(await discover(yarn(), projects(), warnings)).toEqual([])
    expect(CLASSIC_EDGES).toBe(
      ': yarn classic (v1) records no workspaces, so yarn() gives vx no project edges — upgrade to Yarn 2+ (`yarn set version stable`)',
    )
    expect(warnings).toEqual([`yarn.lock${CLASSIC_EDGES}`])
  })
})

function silent(): Logger {
  return {
    runStart() {},
    taskStart() {},
    taskStdout() {},
    taskStderr() {},
    taskComplete() {},
    runStatus() {},
    runEnd() {},
    status() {},
  } as never
}

describe('vx run with bun() declared', () => {
  const BUILD = (inputs: string) =>
    `export default { tasks: { build: { dependsOn: ['^build'], exec: { command: 'echo built' }, cache: { inputs: { files: ${inputs} }, outputs: { files: [] } } }, lint: { exec: { command: 'echo lint' } } } }\n`

  beforeEach(async () => {
    await writeFile(
      path.join(root, 'package.json'),
      JSON.stringify({ name: 'root', private: true, workspaces: ['packages/*'] }),
    )
    // f is a member the lockfile does not list (installed before it was added).
    for (const name of ['a', 'b', 'c', 'd', 'e', 'f']) {
      const dir = path.join(root, 'packages', name)
      await mkdir(path.join(dir, 'src'), { recursive: true })
      await writeFile(path.join(dir, 'package.json'), JSON.stringify({ name, version: '1.0.0' }))
      await writeFile(path.join(dir, 'src', 'index.js'), `// ${name}\n`)
      await writeFile(
        path.join(dir, 'vx.config.mjs'),
        BUILD(name === 'e' ? "['package.json', 'src/**']" : "['src/**']"),
      )
    }
    await writeFile(path.join(root, 'bun.lock'), BUN)
    await Bun.write(
      path.join(root, '.vx/workspace.mjs'),
      localWorkspaceSource(['bun()'], `import { bun } from ${JSON.stringify(PLUGIN_INDEX)}\n`),
    )
    Bun.spawnSync({ cmd: ['git', 'init', '-q'], cwd: root })
  })

  const plan = () => planRun({ cwd: root, tasks: ['build', 'lint'], log: silent() })

  it("orders `^build` by the lockfile's edges, which the manifests do not declare", async () => {
    const tasks = new Map((await plan()).tasks.map((t) => [t.node.id, t.node]))
    expect([...tasks.get('a#build')!.deps].sort()).toEqual(['b#build', 'c#build'])
    expect(tasks.get('b#build')!.deps).toEqual(['e#build'])
    expect(tasks.get('c#build')!.deps).toEqual(['d#build'])
    // d's peer on a would close a cycle: reach, no order.
    expect(tasks.get('d#build')!.deps).toEqual([])
  })

  it("adds each importer's package.json to its cached tasks' inputs, once", async () => {
    const tasks = new Map((await plan()).tasks.map((t) => [t.node.id, t.node]))
    expect(tasks.get('a#build')!.config.cache?.inputs.files).toEqual(['src/**', 'package.json'])
    expect(tasks.get('e#build')!.config.cache?.inputs.files).toEqual(['package.json', 'src/**'])
    // A project the lockfile does not list is no importer: nothing added.
    expect(tasks.get('f#build')!.config.cache?.inputs.files).toEqual(['src/**'])
    // An uncached task gains no cache block: caching stays opt-in.
    expect(tasks.get('a#lint')!.config.cache).toBeUndefined()
  })

  // Probed: the `project` stage the plugin fills does not make a package
  // with no vx.config a planned project.
  it('a package with no vx.config still plans no task', async () => {
    await mkdir(path.join(root, 'packages', 'g'), { recursive: true })
    await writeFile(path.join(root, 'packages', 'g', 'package.json'), JSON.stringify({ name: 'g' }))
    const ids = (await plan()).tasks.map((t) => t.node.id)
    expect(ids).toContain('f#build')
    expect(ids.filter((id) => id.startsWith('g#'))).toEqual([])
  })

  it('an edited package.json re-keys its own tasks and none elsewhere', async () => {
    const hashes = async () =>
      Object.fromEntries((await plan()).tasks.map((t) => [t.node.id, t.hash]))
    const before = await hashes()
    await writeFile(
      path.join(root, 'packages', 'b', 'package.json'),
      JSON.stringify({ name: 'b', version: '1.0.1' }),
    )
    const after = await hashes()
    const moved = Object.keys(after).filter(
      (id) => after[id] !== before[id] && id.endsWith('#build'),
    )
    // a builds after b, so its key folds b's: the cascade, not the input.
    expect(moved.sort()).toEqual(['a#build', 'b#build'])
  })

  // Core reads no manifest edge and diffs no manifest: the dependency an
  // install added reaches `--affected` only as the lockfile's change. Here
  // the lockfile alone records it (these manifests declare none), so no
  // project's own file moved.
  it('--affected after a dependency add selects the dependent through the lockfile diff', async () => {
    await plan() // writes the lock
    commitAll(root)
    const affected = (): string => {
      const r = Bun.spawnSync({
        cmd: [process.execPath, CORE_BIN, 'show', '--affected=HEAD'],
        cwd: root,
        env: { ...process.env, NO_COLOR: '1' },
      })
      expect(r.exitCode).toBe(0)
      return r.stdout.toString()
    }
    expect(affected()).toBe('')
    await writeFile(
      path.join(root, 'bun.lock'),
      BUN.replace(
        '"name": "d", "peerDependencies"',
        '"name": "d", "dependencies": { "e": "workspace:*" }, "peerDependencies"',
      ),
    )
    // d gained e, and c and a build after d; e and b, whose closures did not move, are not.
    expect(affected()).toBe(
      'a  packages/a  2 tasks\nc  packages/c  2 tasks\nd  packages/d  2 tasks\n',
    )
  })

  // package.json is an input now; under the default `immutable` the entry
  // was withheld before it was one too, since core keyed the file already.
  it('a task rewriting its own package.json identically still hits (tsdown), as `mutable` allows', async () => {
    await writeFile(
      path.join(root, 'packages', 'b', 'vx.config.mjs'),
      `export default { tasks: { build: { exec: { command: 'c=$(cat package.json); printf "%s" "$c" > package.json' }, cache: { inputs: { files: ['src/**'] }, outputs: { files: [] }, inputStability: { strategy: 'mutable' } } } } }\n`,
    )
    const once = () =>
      run({ cwd: root, tasks: ['b#build'], log: silent(), handleSignals: false }).then((r) =>
        r.outcomes.map((o) => [o.node.id, o.status]),
      )
    expect(await once()).toEqual([['b#build', 'success']])
    expect(await once()).toEqual([['b#build', 'cache-hit']])
  })
})
