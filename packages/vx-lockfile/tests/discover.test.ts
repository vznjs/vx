/**
 * The projects core found: the root, a, b, c, d (no e, which has no
 * manifest). Their manifests, written here for the plugin to read, record
 * no workspace dependency, only the peers pnpm needs to tell its
 * auto-installed peers apart: the edges below are the lockfile's.
 */
async function projects(
  manifests: Record<string, Record<string, unknown>> = {},
): Promise<ProjectMeta[]> {
  const meta = async (
    name: string,
    dir: string,
    peers?: Record<string, string>,
  ): Promise<ProjectMeta> => {
    await mkdir(dir, { recursive: true })
    const pkg = manifests[name] ?? {
      name,
      ...(peers === undefined ? {} : { peerDependencies: peers }),
    }
    await writeFile(path.join(dir, 'package.json'), JSON.stringify(pkg))
    return { name: path.relative(root, dir) || '//', dir, configPath: null }
  }
  return [
    await meta('root', root),
    await meta('a', path.join(root, 'packages/a'), { c: 'workspace:*' }),
    await meta('b', path.join(root, 'packages/b')),
    await meta('c', path.join(root, 'packages/c')),
    await meta('d', path.join(root, 'packages/d'), { a: 'workspace:*' }),
  ]
}

async function discover(plugin: VxPlugin, metas?: ProjectMeta[], warnings: string[] = []) {
  const ctx: DiscoverContext = {
    workspaceRoot: root,
    cacheDir: path.join(root, '.vx', 'cache'),
    projects: metas ?? (await projects()),
    warn: (m) => warnings.push(m),
    worktreeChanges: async () => null,
  }
  const rel = (dir: string) => path.relative(root, dir) || '.'
  return (await plugin.discover!(ctx)).map((e) => ({
    dir: rel(e.dir),
    name: e.name,
    deps: (e.deps ?? []).map(rel),
    reach: (e.reach ?? []).map(rel),
  }))
}

const EXPECTED = [
  { dir: 'packages/a', name: 'a', deps: ['packages/b', 'packages/c'], reach: [] },
  { dir: 'packages/b', name: 'b', deps: [], reach: [] },
  { dir: 'packages/c', name: 'c', deps: ['packages/b', 'packages/d'], reach: [] },
  { dir: 'packages/d', name: 'd', deps: ['packages/b'], reach: ['packages/a'] },
  { dir: '.', name: 'root', deps: ['packages/b'], reach: [] },
]

describe('discover', () => {
  for (const c of CASES) {
    it(`${c.name}(): importers, names and edges are the lockfile's, not the manifests'`, async () => {
      await writeFile(path.join(root, c.file), c.text)
      expect(await discover(c.make())).toEqual(EXPECTED)
    })
  }

  it('no lockfile: no entries, and says which file it found none of', async () => {
    const warnings: string[] = []
    expect(await discover(bun(), undefined, warnings)).toEqual([])
    // Core's refusal of a `^build` with no edges says to add the plugin already declared.
    expect(warnings).toEqual([
      `[vx] bun(): no bun.lock in ${root} — run \`bun install\`; until then it orders and keys no package's dependencies`,
    ])
  })

  it('a name two importers share is given to neither', async () => {
    await writeFile(path.join(root, 'bun.lock'), BUN)
    const metas = await projects({ b: { name: 'a' } })
    const names = (await discover(bun(), metas)).map((e) => e.name)
    // Ordered by the name each will carry, the path where it has none.
    expect(names).toEqual(['c', 'd', undefined, undefined, 'root'])
  })

  it('bun(): a manifest with no name under a workspaces glob is no workspace, as bun keeps it', async () => {
    // Build output (dist/esm/package.json = {"type":"module"}): bun install
    // leaves it out of bun.lock, so "run `bun install`" never cleared the
    // refusal (Turbo #7025, #7280). Probed on bun 1.4.4: a name that is not
    // a non-empty string is left out; no version is kept.
    await writeFile(path.join(root, 'bun.lock'), BUN)
    const metas = await projects({
      root: { name: 'root', workspaces: ['packages/**'], devDependencies: { b: '*' } },
    })
    for (const [dir, pkg] of [
      ['packages/a/dist/esm', { type: 'module' }],
      ['packages/g', { name: '', version: '1.0.0' }],
      ['packages/h', { name: 5 }],
    ] as const) {
      await mkdir(path.join(root, dir), { recursive: true })
      await writeFile(path.join(root, dir, 'package.json'), JSON.stringify(pkg))
    }
    expect(await discover(bun(), metas)).toEqual(EXPECTED)
    // CONTROL: a name with no version is a workspace bun lists.
    await mkdir(path.join(root, 'packages/f'), { recursive: true })
    await writeFile(path.join(root, 'packages/f/package.json'), JSON.stringify({ name: 'f' }))
    await expect(discover(bun(), metas)).rejects.toThrow(
      'bun.lock is out of date: it does not list the workspace packages/f — run `bun install`',
    )
  })

  it('pnpm(): a lockfile dependency the manifest declares only as a peer is a peer', async () => {
    // pnpm writes an auto-installed peer under `dependencies`; read as an
    // installed entry, d → a closed a → c → d → a and `^build` cycled.
    await writeFile(path.join(root, 'pnpm-lock.yaml'), PNPM)
    const metas = await projects({ a: { name: 'a' }, d: { name: 'd' } })
    const got = await discover(pnpm(), metas)
    expect(got.find((e) => e.dir === 'packages/d')?.deps).toEqual(['packages/a', 'packages/b'])
    expect(await discover(pnpm())).toEqual(EXPECTED)
  })

  it("yarn(): a classic lockfile's edges are the workspaces it links, from their manifests", async () => {
    // Yarn 1 records no workspace in yarn.lock: it links a dependency on a
    // workspace's name and writes no entry for it. A descriptor the file
    // does key (`c@^9.0.0`, a range the workspace does not satisfy) came
    // from the registry. excalidraw: `vx init` wrote yarn(), then
    // `^build` refused for want of project edges (Growth, 2026-10-16).
    await writeFile(
      path.join(root, 'yarn.lock'),
      '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\nc@^9.0.0:\n  version "9.0.0"\n',
    )
    const metas = await projects({
      root: {
        name: 'root',
        private: true,
        workspaces: ['packages/*'],
        devDependencies: { b: '*' },
      },
      a: { name: 'a', dependencies: { b: '1.0.0' }, devDependencies: { c: '1.0.0' } },
      b: { name: 'b', dependencies: { e: '1.0.0' } },
      c: { name: 'c', version: '1.0.0', devDependencies: { d: '^1.0.0' } },
      d: { name: 'd', peerDependencies: { a: '*' } },
    })
    // e is a workspace the root's glob finds but no project yet.
    await mkdir(path.join(root, 'packages/e'), { recursive: true })
    await writeFile(path.join(root, 'packages/e/package.json'), JSON.stringify({ name: 'e' }))
    const warnings: string[] = []
    const got = await discover(yarn(), metas, warnings)
    expect(warnings).toEqual([])
    // As every manager's, and b → e, which the root's glob makes a workspace:
    // e → b, the root's, would close a cycle.
    expect(got).toEqual([
      EXPECTED[0]!,
      { ...EXPECTED[1]!, deps: ['packages/e'] },
      EXPECTED[2]!,
      EXPECTED[3]!,
      { dir: 'packages/e', name: 'e', deps: [], reach: ['packages/b'] },
      EXPECTED[4]!,
    ])
  })

  it('yarn(): a classic workspace a negated glob names is still one, as Yarn 1 links it', async () => {
    // Yarn 1.22 takes no `!` glob: it linked packages/e under `!packages/e`
    // (probed). vx left e out, so b's dependency on it was no edge and b
    // built beside it.
    await writeFile(
      path.join(root, 'yarn.lock'),
      '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n',
    )
    const metas = await projects({
      root: { name: 'root', private: true, workspaces: ['packages/*', '!packages/e'] },
      a: { name: 'a' },
      b: { name: 'b', dependencies: { e: '1.0.0' } },
    })
    await mkdir(path.join(root, 'packages/e'), { recursive: true })
    await writeFile(path.join(root, 'packages/e/package.json'), JSON.stringify({ name: 'e' }))
    const got = await discover(yarn(), metas)
    expect(got.find((p) => p.dir === 'packages/b')?.deps).toEqual(['packages/e'])
    expect(got.find((p) => p.dir === 'packages/e')?.name).toBe('e')
  })

  for (const c of CASES) {
    const workspaces = async (): Promise<void> => {
      if (c.name === 'pnpm') {
        await writeFile(
          path.join(root, 'pnpm-workspace.yaml'),
          "packages:\n  - packages/*\n  - '!**/fixtures/**'\n",
        )
      }
    }
    const rootPkg = { name: 'root', workspaces: ['packages/*'], devDependencies: { b: '*' } }

    it(`${c.name}(): a workspace the lockfile does not list yet refuses until the install`, async () => {
      // A renamed folder, or lerna's 31 added Nx projects: named by its path,
      // the workspace lost every edge, ran beside what it builds on and hit
      // with old content (Growth, stale-lockfile-drops-edges.sh).
      await writeFile(path.join(root, c.file), c.text)
      await workspaces()
      const metas = await projects({ root: rootPkg })
      expect(await discover(c.make(), metas)).toEqual(EXPECTED)
      // CONTROL: a directory a negated glob or node_modules excludes is no workspace.
      for (const dir of ['packages/a/fixtures/x', 'packages/a/node_modules/y']) {
        await mkdir(path.join(root, dir), { recursive: true })
        await writeFile(path.join(root, dir, 'package.json'), JSON.stringify({ name: 'x' }))
      }
      if (c.name === 'pnpm') {
        expect(await discover(c.make(), metas)).toEqual(EXPECTED)
        // A `**` ending a negated glob matches zero directories, as pnpm
        // reads it: `packages/fixtures` is no workspace, and the lock was
        // refused as out of date for it until any install, forever.
        await mkdir(path.join(root, 'packages/fixtures'), { recursive: true })
        await writeFile(
          path.join(root, 'packages/fixtures/package.json'),
          JSON.stringify({ name: 'fx' }),
        )
        expect(await discover(c.make(), metas)).toEqual(EXPECTED)
        await rm(path.join(root, 'packages/fixtures'), { recursive: true })
      }
      await mkdir(path.join(root, 'packages/f'), { recursive: true })
      await writeFile(path.join(root, 'packages/f/package.json'), JSON.stringify({ name: 'f' }))
      const warnings: string[] = []
      await expect(discover(c.make(), metas, warnings)).rejects.toThrow(
        `${c.file} is out of date: it does not list the workspace packages/f — run \`${c.name} install\``,
      )
      expect(warnings).toEqual([])
    })

    if (c.name !== 'yarn') {
      it(`${c.name}(): a workspace a negated glob excludes under a globstar is no workspace`, async () => {
        // `packages/**` with `!**/test/**`: the manager drops packages/a/test
        // (pnpm 10, npm 10, bun 1.4 probed), but the negation was matched
        // against the bare dir, which `**/test/**` does not match, so the
        // lock refused a lockfile the install had just written.
        await writeFile(path.join(root, c.file), c.text)
        const globs = ['packages/**', '!**/test/**']
        if (c.name === 'pnpm') {
          await writeFile(
            path.join(root, 'pnpm-workspace.yaml'),
            `packages:\n${globs.map((g) => `  - '${g}'\n`).join('')}`,
          )
        }
        const metas = await projects({ root: { ...rootPkg, workspaces: globs } })
        await mkdir(path.join(root, 'packages/a/test'), { recursive: true })
        await writeFile(path.join(root, 'packages/a/test/package.json'), '{"name":"a-test"}')
        expect(await discover(c.make(), metas)).toEqual(EXPECTED)
      })

      it(`${c.name}(): a directory a negated globstar names is no workspace, itself included`, async () => {
        // `!**/test/**` drops packages/test itself for pnpm 10, npm 10 and
        // bun 1.4 (each probed: no importer for it), but Bun.Glob's `**`
        // takes no empty tail, so the staleness check named it a workspace
        // the lockfile lacked and refused every run.
        await writeFile(path.join(root, c.file), c.text)
        const globs = ['packages/*', '!**/test/**', '!packages/skip']
        if (c.name === 'pnpm') {
          await writeFile(
            path.join(root, 'pnpm-workspace.yaml'),
            `packages:\n${globs.map((g) => `  - '${g}'\n`).join('')}`,
          )
        }
        const metas = await projects({ root: { ...rootPkg, workspaces: globs } })
        for (const dir of ['packages/test', 'packages/skip']) {
          await mkdir(path.join(root, dir), { recursive: true })
          await writeFile(path.join(root, dir, 'package.json'), JSON.stringify({ name: 'x' }))
        }
        expect(await discover(c.make(), metas)).toEqual(EXPECTED)
        // CONTROL: a directory no negation names is still a workspace it lacks.
        await mkdir(path.join(root, 'packages/tested'), { recursive: true })
        await writeFile(path.join(root, 'packages/tested/package.json'), '{"name":"y"}')
        await expect(discover(c.make(), metas)).rejects.toThrow(
          `${c.file} is out of date: it does not list the workspace packages/tested`,
        )
      })
    }

    if (c.name === 'pnpm') {
      it('pnpm(): a manifest under bower_components is no workspace', async () => {
        // pnpm's own walk skips `**/bower_components/**` as it does
        // node_modules (probed, pnpm 10.28); npm and bun list it.
        await writeFile(path.join(root, c.file), c.text)
        await writeFile(path.join(root, 'pnpm-workspace.yaml'), "packages:\n  - 'packages/**'\n")
        const metas = await projects({ root: rootPkg })
        await mkdir(path.join(root, 'packages/a/bower_components/z'), { recursive: true })
        await writeFile(
          path.join(root, 'packages/a/bower_components/z/package.json'),
          '{"name":"z"}',
        )
        expect(await discover(c.make(), metas)).toEqual(EXPECTED)
      })
    }

    it(`${c.name}(): a manifest dependency on a workspace the lockfile lacks refuses until the install`, async () => {
      // c gained "a" in package.json before the install: no edge, so c built
      // beside a and hit with a's old output.
      await writeFile(path.join(root, c.file), c.text)
      await workspaces()
      const metas = await projects({
        root: rootPkg,
        c: { name: 'c', dependencies: { a: '*' }, devDependencies: { d: '*' } },
      })
      await expect(discover(c.make(), metas)).rejects.toThrow(
        `${c.file} is out of date: it does not list packages/c's dependency on a — run \`${c.name} install\``,
      )
      // CONTROL: one it records, under any field, and a name no workspace carries.
      const ok = await projects({
        root: rootPkg,
        a: { name: 'a', dependencies: { b: '*', left: '1' }, peerDependencies: { c: '*' } },
        c: { name: 'c', devDependencies: { d: '*' } },
      })
      expect(await discover(c.make(), ok)).toEqual(EXPECTED)
    })

    it(`${c.name}(): the names the lockfile records are read once per content`, async () => {
      // Parsing them was ~2 ms of every warm run on solid; only the
      // lockfile text decides them, so they are kept under its hash.
      await writeFile(path.join(root, c.file), c.text)
      await workspaces()
      const metas = await projects({
        root: rootPkg,
        a: { name: 'a', dependencies: { b: '*' }, peerDependencies: { c: '*' } },
        c: { name: 'c', devDependencies: { d: '*' } },
      })
      expect(await discover(c.make(), metas)).toEqual(EXPECTED)
      // The kept names are what the next run reads: emptied, they refuse.
      const memo = path.join(root, '.vx/cache/lockfile-claims', `${c.file}.recorded.json`)
      const kept = (await Bun.file(memo).json()) as { names: Record<string, string[]> }
      for (const i of Object.keys(kept.names)) kept.names[i] = []
      await writeFile(memo, JSON.stringify(kept))
      await expect(discover(c.make(), metas)).rejects.toThrow(`${c.file} is out of date`)
      // An edit to the lockfile reads it afresh.
      await writeFile(path.join(root, c.file), `${c.text}\n`)
      expect(await discover(c.make(), metas)).toEqual(EXPECTED)
    })

    it(`${c.name}(): a package.json that does not parse refuses, naming it`, async () => {
      // Read as no manifest, a conflicted one lost its dependencies: b ran
      // beside a and hit with a's old output while lock and --check passed
      // (Growth, conflicted-package-json-drops-edge.sh). Turbo and Nx refuse.
      await writeFile(path.join(root, c.file), c.text)
      await workspaces()
      const metas = await projects({ root: rootPkg })
      const b = path.join(root, 'packages/b/package.json')
      await writeFile(b, '<<<<<<< HEAD\n{"name":"b"}\n=======\n{"name":"b"}\n>>>>>>> x\n')
      await expect(discover(c.make(), metas)).rejects.toThrow(
        'packages/b/package.json: holds git merge conflict markers — resolve them',
      )
      await writeFile(b, '{"name":')
      await expect(discover(c.make(), metas)).rejects.toThrow('packages/b/package.json: not JSON (')
      await writeFile(b, '[]')
      await expect(discover(c.make(), metas)).rejects.toThrow(
        'packages/b/package.json: not a JSON object',
      )
      await writeFile(b, JSON.stringify({ name: 'b' }))
      await writeFile(path.join(root, 'package.json'), '<<<<<<< HEAD\n{}\n=======\n{}\n>>>>>>> x\n')
      await expect(discover(c.make(), metas)).rejects.toThrow(
        /^package\.json: holds git merge conflict markers — resolve them$/,
      )
    })

    it(`${c.name}(): a package.json with a trailing comma and a comment reads as ${c.name} reads it`, async () => {
      // `bun install` takes a manifest with a trailing comma or a comment;
      // npm, pnpm and yarn refuse one. bun() refused it as "not JSON", so a
      // workspace bun installed could not be locked.
      await writeFile(path.join(root, c.file), c.text)
      await workspaces()
      const metas = await projects({
        root: rootPkg,
        a: { name: 'a', dependencies: { b: '*' }, peerDependencies: { c: '*' } },
        c: { name: 'c', devDependencies: { d: '*' } },
      })
      await writeFile(
        path.join(root, 'packages/a/package.json'),
        '{\n  // a\n  "name": "a",\n  "dependencies": { "b": "*", },\n  "peerDependencies": { "c": "*" },\n}\n',
      )
      if (c.name === 'bun') expect(await discover(c.make(), metas)).toEqual(EXPECTED)
      else
        await expect(discover(c.make(), metas)).rejects.toThrow(
          'packages/a/package.json: not JSON (',
        )
    })
  }

  it('pnpm(): a lockfile per package (sharedWorkspaceLockfile: false) refuses, naming the setting', async () => {
    // pnpm writes one pnpm-lock.yaml per package and the root's lists only
    // `.`: "run `pnpm install`" rewrote the same files, so the refusal
    // looped (turborepo#14874). Core claims only root files, so pnpm()
    // cannot key a package's own lockfile and says so.
    const ROOT_ONLY = "lockfileVersion: '9.0'\n\nimporters:\n\n  .: {}\n"
    await writeFile(path.join(root, 'pnpm-lock.yaml'), ROOT_ONLY)
    const metas = await projects({ root: { name: 'root' } })
    const unshared =
      'pnpm-lock.yaml lists no workspace package: shared-workspace-lockfile is false, so pnpm writes a pnpm-lock.yaml per package, which pnpm() does not read — remove the setting and run `pnpm install`'
    for (const [file, text] of [
      ['pnpm-workspace.yaml', 'packages:\n  - packages/*\nsharedWorkspaceLockfile: false\n'],
      ['.npmrc', 'shared-workspace-lockfile = false\n'],
    ] as const) {
      await writeFile(path.join(root, 'pnpm-workspace.yaml'), 'packages:\n  - packages/*\n')
      await writeFile(path.join(root, file), text)
      await expect(discover(pnpm(), metas)).rejects.toThrow(unshared)
      await rm(path.join(root, '.npmrc'), { force: true })
    }
    // CONTROL: the workspace file's `true` wins over .npmrc, as pnpm 10 has it.
    await writeFile(
      path.join(root, 'pnpm-workspace.yaml'),
      'packages:\n  - packages/*\nsharedWorkspaceLockfile: true\n',
    )
    await writeFile(path.join(root, '.npmrc'), 'shared-workspace-lockfile=false\n')
    await expect(discover(pnpm(), metas)).rejects.toThrow('pnpm-lock.yaml is out of date')
    // CONTROL: a shared lockfile the setting did not split (pnpm < 10.8
    // reads no pnpm-workspace.yaml setting) reads as ever.
    await rm(path.join(root, '.npmrc'))
    await writeFile(
      path.join(root, 'pnpm-workspace.yaml'),
      'packages:\n  - packages/*\nsharedWorkspaceLockfile: false\n',
    )
    await writeFile(path.join(root, 'pnpm-lock.yaml'), PNPM)
    expect(await discover(pnpm(), await projects())).toEqual(EXPECTED)
  })

  it('yarn(): a classic dependency on a range the workspace misses is the registry copy', async () => {
    await writeFile(
      path.join(root, 'yarn.lock'),
      '# yarn lockfile v1\n\n\nb@^9.0.0:\n  version "9.0.0"\n',
    )
    const metas = await projects({
      root: { name: 'root', private: true, workspaces: { packages: ['packages/*'] } },
      a: { name: 'a', dependencies: { b: '^9.0.0' } },
    })
    expect((await discover(yarn(), metas)).find((e) => e.dir === 'packages/a')?.deps).toEqual([])
  })

  it('yarn(): a classic root `resolutions` range the workspace misses is the registry copy', async () => {
    // Yarn 1.22 with `"**/ms": "2.1.3"` and a workspace ms at 2.1.2:
    // every ms request asks for 2.1.3, the file keys `ms@2.1.3` alone, and
    // node_modules/ms is the registry copy. a's own `^2.1.1` is keyed
    // nowhere, so it read as the workspace link.
    await writeFile(
      path.join(root, 'yarn.lock'),
      '# yarn lockfile v1\n\n\nms@2.1.3:\n  version "2.1.3"\n',
    )
    const metas = await projects({
      root: {
        name: 'root',
        private: true,
        workspaces: ['packages/*'],
        resolutions: { '**/ms': '2.1.3', 'other/**/b': '9.0.0' },
      },
      a: { name: 'a', dependencies: { ms: '^2.1.1', b: '*' } },
      b: { name: 'b', version: '1.0.0' },
      c: { name: 'ms', version: '2.1.2' },
    })
    const got = await discover(yarn(), metas)
    expect(got.find((e) => e.dir === 'packages/a')?.deps).toEqual(['packages/b'])
  })

  it('yarn(): a classic `file:` dependency on a workspace is a copy, no link', async () => {
    // Yarn 1.22 keys `"c@file:packages/c"` and copies it into
    // packages/a/node_modules/c, as berry's `file:` (`linkedDir`).
    await writeFile(
      path.join(root, 'yarn.lock'),
      '# yarn lockfile v1\n\n\n"c@file:packages/c":\n  version "1.0.0"\n',
    )
    const metas = await projects({
      root: { name: 'root', private: true, workspaces: ['packages/*'] },
      a: { name: 'a', dependencies: { b: 'link:../b', c: 'file:../c' } },
    })
    const got = await discover(yarn(), metas)
    expect(got.find((e) => e.dir === 'packages/a')?.deps).toEqual(['packages/b'])
  })

  it('yarn(): a classic root `resolutions` range the workspace satisfies stays a link', async () => {
    await writeFile(path.join(root, 'yarn.lock'), '# yarn lockfile v1\n\n\n')
    const metas = await projects({
      root: {
        name: 'root',
        private: true,
        workspaces: ['packages/*'],
        resolutions: { ms: '2.1.2' },
      },
      a: { name: 'a', dependencies: { ms: '^2.1.1' } },
      c: { name: 'ms', version: '2.1.2' },
    })
    const got = await discover(yarn(), metas)
    expect(got.find((e) => e.dir === 'packages/a')?.deps).toEqual(['packages/c'])
  })
})

function silent(): Logger {
  return {
    runStart() {},
    taskStart() {},
    taskStdout() {},
    taskStderr() {},
    taskComplete() {},
    runStatus() {},
    runEnd() {},
    status() {},
  } as never
}

describe('vx run with bun() declared', () => {
  const BUILD = (inputs: string) =>
    `export default { tasks: { build: { dependsOn: ['^build'], exec: { command: 'echo built' }, inputs: { files: ${inputs} }, cache: { outputs: { files: [] } } }, lint: { exec: { command: 'echo lint' }, inputs: { files: ['src/**'] } } } }\n`

  beforeEach(async () => {
    await writeFile(
      path.join(root, 'package.json'),
      JSON.stringify({ name: 'root', private: true, workspaces: ['packages/*'] }),
    )
    // f is a project outside the workspaces, so no importer.
    for (const name of ['a', 'b', 'c', 'd', 'e', 'f']) {
      const dir = path.join(root, name === 'f' ? 'tools' : 'packages', name)
      await mkdir(path.join(dir, 'src'), { recursive: true })
      await writeFile(path.join(dir, 'package.json'), JSON.stringify({ name, version: '1.0.0' }))
      await writeFile(path.join(dir, 'src', 'index.js'), `// ${name}\n`)
      await writeFile(
        path.join(dir, 'vx.config.mjs'),
        BUILD(name === 'e' ? "['package.json', 'src/**']" : "['src/**']"),
      )
    }
    await writeFile(path.join(root, 'bun.lock'), BUN)
    await Bun.write(
      path.join(root, '.vx/workspace.mjs'),
      localWorkspaceSource(['bun()'], `import { bun } from ${JSON.stringify(PLUGIN_INDEX)}\n`),
    )
    Bun.spawnSync({ cmd: ['git', 'init', '-q'], cwd: root })
  })

  const plan = () => planRun({ cwd: root, tasks: ['build', 'lint'], log: silent() })

  it("orders `^build` by the lockfile's edges, which the manifests do not declare", async () => {
    const tasks = new Map((await plan()).tasks.map((t) => [t.node.id, t.node]))
    expect([...tasks.get('a#build')!.deps].sort()).toEqual(['b#build', 'c#build'])
    expect(tasks.get('b#build')!.deps).toEqual(['e#build'])
    // The root installs b, so every project builds after it.
    expect([...tasks.get('c#build')!.deps].sort()).toEqual(['b#build', 'd#build'])
    // d's peer on a would close a cycle: reach, no order.
    expect(tasks.get('d#build')!.deps).toEqual(['b#build'])
  })

  it("adds each importer's package.json to its cached tasks' inputs, once", async () => {
    const tasks = new Map((await plan()).tasks.map((t) => [t.node.id, t.node]))
    expect(tasks.get('a#build')!.config.inputs?.files).toEqual(['src/**', 'package.json'])
    expect(tasks.get('e#build')!.config.inputs?.files).toEqual(['package.json', 'src/**'])
    // A project outside the workspaces is no importer: nothing added,
    // and no name given, so its path names it.
    expect(tasks.get('tools/f#build')!.config.inputs?.files).toEqual(['src/**'])
    // An uncached task is keyed all the same, and gains no cache block:
    // caching stays opt-in.
    expect(tasks.get('a#lint')!.config.inputs?.files).toEqual(['src/**', 'package.json'])
    expect(tasks.get('a#lint')!.config.cache).toBeUndefined()
  })

  // Probed: the `project` stage the plugin fills does not make a package
  // with no vx.config a planned project.
  it('a package with no vx.config still plans no task', async () => {
    await mkdir(path.join(root, 'tools', 'g'), { recursive: true })
    await writeFile(path.join(root, 'tools', 'g', 'package.json'), JSON.stringify({ name: 'g' }))
    const ids = (await plan()).tasks.map((t) => t.node.id)
    expect(ids).toContain('tools/f#build')
    expect(ids.filter((id) => id.startsWith('g#'))).toEqual([])
  })

  it('an edited package.json re-keys its own tasks and none elsewhere', async () => {
    const hashes = async () =>
      Object.fromEntries((await plan()).tasks.map((t) => [t.node.id, t.hash]))
    const before = await hashes()
    await writeFile(
      path.join(root, 'packages', 'b', 'package.json'),
      JSON.stringify({ name: 'b', version: '1.0.1' }),
    )
    const after = await hashes()
    const moved = Object.keys(after).filter(
      (id) => after[id] !== before[id] && id.endsWith('#build'),
    )
    // a, c and d build after b, so their keys include b's: the cascade, not
    // the input. The root installs b, so c and d reach it too.
    expect(moved.sort()).toEqual(['a#build', 'b#build', 'c#build', 'd#build'])
  })

  // Core reads no manifest edge and diffs no manifest: the dependency an
  // install added reaches `--affected` only as the lockfile's change. Here
  // the lockfile alone records it (these manifests declare none), so no
  // project's own file moved.
  it('--affected after a dependency add selects the dependent through the lockfile diff', async () => {
    await plan() // writes the lock
    commitAll(root)
    const affected = (): string => {
      const r = Bun.spawnSync({
        cmd: [process.execPath, CORE_BIN, 'show', '--affected=HEAD'],
        cwd: root,
        env: { ...process.env, NO_COLOR: '1' },
      })
      expect(r.exitCode).toBe(0)
      return r.stdout.toString()
    }
    expect(affected()).toBe('')
    await writeFile(
      path.join(root, 'bun.lock'),
      BUN.replace(
        '"name": "d", "peerDependencies"',
        '"name": "d", "dependencies": { "e": "workspace:*" }, "peerDependencies"',
      ),
    )
    // d gained e, and c and a build after d; e and b, whose closures did not move, are not.
    expect(affected()).toBe(
      '  project  dir         tasks\n' +
        '  a        packages/a  2 tasks\n' +
        '  c        packages/c  2 tasks\n' +
        '  d        packages/d  2 tasks\n',
    )
  })

  // package.json is an input now; under the default `immutable` the entry
  // was withheld before it was one too, since core keyed the file already.
  it('a task rewriting its own package.json identically still hits (tsdown), as `mutable` allows', async () => {
    await writeFile(
      path.join(root, 'packages', 'b', 'vx.config.mjs'),
      `export default { tasks: { build: { exec: { command: 'c=$(cat package.json); printf "%s" "$c" > package.json' }, inputs: { files: ['src/**'] }, cache: { outputs: { files: [] }, inputStability: { strategy: 'mutable' } } } } }\n`,
    )
    const once = () =>
      run({ cwd: root, tasks: ['b#build'], log: silent(), handleSignals: false }).then((r) =>
        r.outcomes.map((o) => [o.node.id, o.status]),
      )
    expect(await once()).toEqual([['b#build', 'success']])
    expect(await once()).toEqual([['b#build', 'cache-hit']])
  })
})

// Core keys no package file: `package.json` reaches a key only as the
// input bun() adds. The same edit, the same workspace, with and without it.
describe('a package.json edit re-keys a cached task only through the plugin', () => {
  const setup = async (plugins: string[]): Promise<void> => {
    await writeFile(
      path.join(root, 'package.json'),
      JSON.stringify({ name: 'root', private: true, workspaces: ['packages/*'] }),
    )
    for (const name of ['a', 'b', 'c', 'd', 'e']) {
      const dir = path.join(root, 'packages', name)
      await mkdir(path.join(dir, 'src'), { recursive: true })
      await writeFile(path.join(dir, 'package.json'), JSON.stringify({ name, version: '1.0.0' }))
      await writeFile(path.join(dir, 'src', 'index.js'), `// ${name}\n`)
      await writeFile(
        path.join(dir, 'vx.config.mjs'),
        `export default { tasks: { build: { exec: { command: 'echo built' }, inputs: { files: ['src/**'] }, cache: { outputs: { files: [] } } } } }\n`,
      )
    }
    await writeFile(path.join(root, 'bun.lock'), BUN)
    await Bun.write(
      path.join(root, '.vx/workspace.mjs'),
      localWorkspaceSource(plugins, `import { bun } from ${JSON.stringify(PLUGIN_INDEX)}\n`),
    )
    Bun.spawnSync({ cmd: ['git', 'init', '-q'], cwd: root })
  }
  // bun() names b; with no plugin its path does.
  const bKey = async (): Promise<string | undefined> =>
    (await planRun({ cwd: root, tasks: ['build'], log: silent() })).tasks.find(
      (t) => t.node.id === 'b#build' || t.node.id === 'packages/b#build',
    )?.hash
  const bump = () =>
    writeFile(
      path.join(root, 'packages', 'b', 'package.json'),
      JSON.stringify({ name: 'b', version: '1.0.1' }),
    )

  it('with bun() declared, the edit moves the key', async () => {
    await setup(['bun()'])
    const before = await bKey()
    await bump()
    expect(await bKey()).not.toBe(before)
  })

  it('with no plugin declared, the edit moves no key', async () => {
    await setup([])
    const before = await bKey()
    expect(before).toBeDefined()
    await bump()
    expect(await bKey()).toBe(before)
  })
})
