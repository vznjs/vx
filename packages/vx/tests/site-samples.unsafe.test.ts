/**
 * Every hand-authored page of the site — guides, concepts, blog, the
 * top-level pages — and none of the ones `import-docs.ts` generates from
 * `packages/vx/docs`. A class pin that LISTS its pages only holds the pages
 * someone remembered; one that finds them holds the class.
 */
function handAuthoredSitePages(): string[] {
  const pages: string[] = []
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (entry.name !== 'design' && entry.name !== 'modules') walk(p)
      } else if (/\.mdx?$/.test(entry.name)) {
        const text = readFileSync(p, 'utf8')
        if (!text.includes('# generated by packages/vx-docs/scripts/import-docs.ts')) pages.push(p)
      }
    }
  }
  walk(DOCS)
  return pages
}

/**
 * A Docs page's `## heading` section, up to the next `## `: the six Docs
 * pages each hold several topics (design/site-short-2026-09.md), and a pin
 * that reads a whole page lets one topic's rows answer for another's.
 */
function section(page: string, heading: string): string {
  const start = page.indexOf(`\n## ${heading}\n`)
  expect(start).toBeGreaterThan(-1)
  const end = page.indexOf('\n## ', start + 1)
  return page.slice(start, end === -1 ? undefined : end)
}

function fencedBlock(page: string, lang: string, firstLine: string): string {
  const open = `\`\`\`${lang}\n${firstLine}`
  const start = page.indexOf(open)
  expect(start).toBeGreaterThan(-1)
  const body = start + lang.length + 4
  const end = page.indexOf('```', body)
  return page.slice(body, end)
}

