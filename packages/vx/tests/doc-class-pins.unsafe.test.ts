// The formatter reflows prose, and a reflow can break the markdown under it:
// schema.md's "(the count of names + the names themselves …)" wrapped so the
// `+` landed at the start of a line, and oxfmt turned it into a BULLET in the
// middle of a sentence — which is how it shipped to the site (item 357,
// 2026-09-19). A paragraph whose parentheses do not balance is the signature
// of that class, and cheap to check on every page at once.
describe('no prose block was broken open by a reflow', () => {
  it('every paragraph and list item closes the parentheses it opens', () => {
    const broken: string[] = []
    const pages = handAuthoredDocs()
    expect(pages.length).toBeGreaterThan(40)
    for (const page of pages) {
      const text = readFileSync(page, 'utf8')
      let fenced = false
      let block: string[] = []
      let start = 0
      const flush = (): void => {
        if (block.length === 0) return
        // Code spans hold shell and glob punctuation that is not prose.
        const prose = block
          .join('\n')
          .replace(/`[^`]*`/g, '')
          .replace(/`[^`]*$/, '')
        if (prose.split('(').length !== prose.split(')').length) {
          broken.push(`${path.basename(page)}:${start}`)
        }
        block = []
      }
      text.split('\n').forEach((line, i) => {
        if (line.trim().startsWith('```')) {
          fenced = !fenced
          flush()
          return
        }
        if (fenced) return
        if (line.trim() === '') {
          flush()
          return
        }
        if (block.length === 0) start = i + 1
        block.push(line)
      })
      flush()
    }
    expect(broken).toEqual([])
  })
})

