// rather than one page against its source. They grew up inside
// site-samples.unsafe.test.ts because that file already read both doc trees,
// and by item 361 it carried 226 of the suite's 411 assertions and every one
// of these. That is why item 358's pin landed in the wrong suite and why the
// shared helper had to be added to a file named for renderer samples.
//
// They live here now, over one contract: `handAuthoredDocs()` is the page
// list, `CLASS_PAGES` names what each narrowing filter actually reaches. A
// move, not a rewrite — item 365 (2026-09-19) held the assertion count across
// it, so nothing was dropped in the carry.
