/**
 * Every markdown page a person wrote, in both doc trees. `history/` and
 * `design/` are records of what was true then, STATUS.md quotes old wording
 * on purpose, and the site's copies of `packages/vx/docs` are rewritten by
 * the docs build — a class grep that reads them finds its own fix twice.
 */
function handAuthoredDocs(): string[] {
  const pages: string[] = []
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (entry.name !== 'history' && entry.name !== 'design') walk(p)
      } else if (entry.name.endsWith('.md') && entry.name !== 'STATUS.md') {
        const text = readFileSync(p, 'utf8')
        if (!text.includes('# generated by packages/vx-docs/scripts/import-docs.ts')) pages.push(p)
      }
    }
  }
  for (const root of [DOCS, path.resolve(import.meta.dir, '..', 'docs')]) walk(root)
  return pages
}

