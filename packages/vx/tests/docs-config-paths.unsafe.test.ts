// M 2026-11-23, "settings. Why things are not matched?": a page named
// `cache.outputs` and `inputStability`, fields no config takes. Every config
// path a user page quotes in prose (`run.timeout`, `exec.env.passThrough`) is
// one the config contract or the settings list holds; fences are
// docs-examples' and config-corpus' law. Unsafe: it reads vx-docs and the
// plugin READMEs.

import { existsSync, readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { expect, it } from 'bun:test'
import { SETTINGS } from '../src/settings.js'

const CORE = path.resolve(import.meta.dir, '..')
const REPO = path.resolve(CORE, '../..')

type Schema = Record<string, { levels?: Record<string, string[]> }>
const schema = JSON.parse(
  readFileSync(path.join(CORE, 'tests/contract/config-schema.json'), 'utf8'),
) as Schema

const real = new Set(SETTINGS.map((s) => s.path))
for (const { levels } of Object.values(schema))
  for (const [level, keys] of Object.entries(levels ?? {}))
    for (const k of keys)
      real.add(`${level === '' ? '' : `${level}.`}${k}`.replace(/^tasks\.\*\./, ''))

/** A path or its tail (`persistent.readyWhen` of `exec.persistent.readyWhen`). */
const known = (p: string): boolean =>
  [...real].some((r) => r === p || r.endsWith(`.${p}`) || r.startsWith(`${p}.`))

/** Not config: files, API members and other tools' keys a page quotes. */
const NOT_CONFIG = new Set([
  'cache.removing',
  'cache.close',
  'cache.get',
  'cache.has',
  // vx info's JSON field.
  'sandbox.untraced',
  // Vite Task's.
  'run.tasks',
])

/** Pages about other tools' configs, or vx's history and internals. */
const SKIP_DIRS = ['node_modules', 'history', 'design', 'blog', 'releases', 'modules', 'upgrading']
const SKIP_PAGES =
  /(architecture|optimizations|patterns|flows|upstream-ledger|STATUS|upgrading|comparison|parity|migrate|api)\.mdx?$/

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) return SKIP_DIRS.includes(e.name) ? [] : walk(p)
    return /\.mdx?$/.test(e.name) && !SKIP_PAGES.test(e.name) ? [p] : []
  })
}

const pages = [
  ...walk(path.join(CORE, 'docs')),
  ...walk(path.join(REPO, 'private/vx-docs/src/content/docs')),
  path.join(REPO, 'skills/vx/SKILL.md'),
  ...readdirSync(path.join(REPO, 'packages'))
    .filter((p) => p !== 'vx-migrate')
    .map((p) => path.join(REPO, 'packages', p, 'README.md'))
    .filter(existsSync),
]

const ROOTS = 'run|cache|inputs|outputs|exec|watch|history|lock|persistent|sandbox'
const PATH = new RegExp(`^((?:${ROOTS})\\.[a-zA-Z]+(?:\\.[a-zA-Z]+)*)(?:[ :=(].*)?$`)

it('quotes only config paths vx takes', () => {
  const bad: string[] = []
  for (const file of pages) {
    const text = readFileSync(file, 'utf8')
    if (text.includes('# generated by private/vx-docs/scripts/import-docs.ts')) continue
    // Fences are other laws'; inline code outside them is this one's.
    const prose = text.replace(/^```[\s\S]*?^```/gm, '')
    for (const m of prose.matchAll(/`([^`\n]+)`/g)) {
      const p = PATH.exec(m[1]!)?.[1]
      if (p === undefined || NOT_CONFIG.has(p) || /\.(ts|md|db|lock|json|mjs|js)$/.test(p)) continue
      if (!known(p)) bad.push(`${path.relative(REPO, file)}: ${p}`)
    }
  }
  expect(bad).toEqual([])
})
